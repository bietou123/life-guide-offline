import puppeteer from 'puppeteer-core';
import path from 'node:path';
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const url = process.argv[2] || 'http://127.0.0.1:5201/';
const scheme = process.argv[3] || 'light';
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--disable-gpu','--no-sandbox','--hide-scrollbars'] });
const page = await browser.newPage();
await page.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: scheme }]);
await page.evaluateOnNewDocument(() => { try { localStorage.clear(); } catch {} });
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await page.goto(url, { waitUntil: 'networkidle0' });
await new Promise(r => setTimeout(r, 800));
await page.click('#btn-menu');
await new Promise(r => setTimeout(r, 350));
await page.screenshot({ path: path.resolve('shots', `panel-${scheme}-drawer.png`) });
await page.click('#btn-open-reader');
await new Promise(r => setTimeout(r, 600));
await page.screenshot({ path: path.resolve('shots', `panel-${scheme}-reader.png`) });
await browser.close();
